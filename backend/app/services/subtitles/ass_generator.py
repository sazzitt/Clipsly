"""Advanced SubStation Alpha (ASS v4.00+) Subtitle Document Generator.

Transforms persisted SubtitleTrack and SubtitleEvent database entities into
canonical, UTF-8 encoded ASS subtitle documents with word-level karaoke timing tags.

Specifications:
- Canvas: 1080x1920 vertical video (PlayResX: 1080, PlayResY: 1920).
- Format: ASS v4.00+ conforming to libass parser standards.
- Word Karaoke Tags: {\\kf<dur_cs>} (progressive sweep) or {\\k<dur_cs>} (instant).
- Precision Loss: Centisecond (10ms) quantization handled with deterministic rounding.
- Edge Case Protection: 2ms/pathological events grouped into untimed text fallback.
- Text Safety: All spoken text sanitized to prevent override-tag injection.
"""

import json
import logging
from typing import Any, Dict, List, Optional

from backend.app.models.subtitle_event import SubtitleEvent
from backend.app.models.subtitle_track import SubtitleTrack
from backend.app.services.subtitles.ass_escape import sanitize_ass_text, sanitize_word_token
from backend.app.services.subtitles.ass_timing import (
    format_dialogue_interval,
    ms_to_centiseconds,
)

logger = logging.getLogger("clipsly.subtitles.ass_generator")

# Default 1080x1920 Vertical Caption Style (Karaoke Amber standard)
DEFAULT_STYLE_NAME = "Default"
DEFAULT_FONT_NAME = "Montserrat"
DEFAULT_FONT_SIZE = 88
DEFAULT_PRIMARY_COLOR = "&H00FFFFFF"     # Solid White (Post-karaoke / spoken text)
DEFAULT_SECONDARY_COLOR = "&H0000D7FF"   # Warm Gold / Amber (Pre-karaoke / active sweep target)
DEFAULT_OUTLINE_COLOR = "&H00000000"     # Solid Black
DEFAULT_BACK_COLOR = "&H80000000"        # 50% Semi-transparent black drop shadow
DEFAULT_OUTLINE_WIDTH = 8.0
DEFAULT_SHADOW_DEPTH = 3.0
DEFAULT_MARGIN_V = 380                   # Safe vertical zone from bottom


class AssDocumentError(ValueError):
    """Raised when ASS document generation or validation fails."""
    pass


def build_script_info_section(title: str = "Clipsly Video Captions") -> str:
    """Generates the canonical [Script Info] section locked to 1080x1920 resolution."""
    lines = [
        "[Script Info]",
        f"; Script generated by Clipsly Subtitle Engine v18.3",
        f"Title: {title}",
        "ScriptType: v4.00+",
        "WrapStyle: 0",
        "ScaledBorderAndShadow: yes",
        "YCbCr Matrix: TV.709",
        "PlayResX: 1080",
        "PlayResY: 1920",
        "",
    ]
    return "\n".join(lines)


def build_v4_styles_section(
    style_name: str = DEFAULT_STYLE_NAME,
    font_name: str = DEFAULT_FONT_NAME,
    font_size: int = DEFAULT_FONT_SIZE,
    primary_color: str = DEFAULT_PRIMARY_COLOR,
    secondary_color: str = DEFAULT_SECONDARY_COLOR,
    outline_color: str = DEFAULT_OUTLINE_COLOR,
    back_color: str = DEFAULT_BACK_COLOR,
    outline_width: float = DEFAULT_OUTLINE_WIDTH,
    shadow_depth: float = DEFAULT_SHADOW_DEPTH,
    margin_v: int = DEFAULT_MARGIN_V,
) -> str:
    """Generates the [V4+ Styles] section with format definition and active style."""
    format_line = (
        "Format: Name, Fontname, Fontsize, PrimaryColour, SecondaryColour, OutlineColour, "
        "BackColour, Bold, Italic, Underline, StrikeOut, ScaleX, ScaleY, Spacing, Angle, "
        "BorderStyle, Outline, Shadow, Alignment, MarginL, MarginR, MarginV, Encoding"
    )

    style_line = (
        f"Style: {style_name},{font_name},{font_size},"
        f"{primary_color},{secondary_color},{outline_color},{back_color},"
        f"-1,0,0,0,100,100,2,0.0,1,{outline_width:.1f},{shadow_depth:.1f},"
        f"2,100,100,{margin_v},1"
    )

    lines = [
        "[V4+ Styles]",
        format_line,
        style_line,
        "",
    ]
    return "\n".join(lines)


def format_karaoke_dialogue_text(
    event_text: str,
    words_data: Optional[List[Dict[str, Any]]],
    event_start_ms: int,
    event_dur_cs: int,
    karaoke_tag: str = r"\kf",
) -> str:
    """Generates the text payload with word-level karaoke timing tags for a single dialogue line.

    Extreme Edge Cases Handled:
    1. Empty words array or unparsed words: Emits clean sanitized plain text without tags.
    2. Pathological duration (event_dur_cs < word_count): When duration is too short to give
       each word >= 1cs, emits clean plain text to avoid fabricating non-existent timing precision.
    3. Missing / invalid timestamps: Clamps or falls back gracefully without breaking syntax.
    4. Cumulative duration constraint: Sum of karaoke centiseconds never exceeds event_dur_cs.
    """
    clean_full_text = sanitize_ass_text(event_text)
    if not clean_full_text:
        return ""

    if not words_data or not isinstance(words_data, list) or len(words_data) == 0:
        return clean_full_text

    # Extract valid word tokens
    valid_words: List[Dict[str, Any]] = []
    for item in words_data:
        raw_text = str(item.get("text") or item.get("word") or "").strip()
        if not raw_text:
            continue
        start = int(round(item.get("start_ms", 0)))
        end = int(round(item.get("end_ms", 0)))
        valid_words.append({"text": raw_text, "start_ms": start, "end_ms": end})

    if not valid_words:
        return clean_full_text

    k = len(valid_words)

    # Edge Case: Available centiseconds is smaller than the number of words (e.g. 2ms with 5 words).
    # Centisecond precision cannot represent k words of duration >= 1cs.
    # Fallback: Emit clean plain text as documented in Requirement 6.
    if event_dur_cs < k:
        logger.debug(
            "Event duration (%dcs) smaller than word count (%d). Falling back to plain text.",
            event_dur_cs,
            k,
        )
        return clean_full_text

    # Compute raw centiseconds relative to event start
    raw_durations_cs: List[int] = []
    raw_gaps_cs: List[int] = []
    last_end_ms = event_start_ms

    for w in valid_words:
        w_start = max(event_start_ms, w["start_ms"])
        w_end = max(w_start + 1, w["end_ms"])

        gap_ms = max(0, w_start - last_end_ms)
        dur_ms = max(1, w_end - w_start)

        raw_gaps_cs.append(ms_to_centiseconds(gap_ms))
        raw_durations_cs.append(max(1, ms_to_centiseconds(dur_ms)))
        last_end_ms = w_end

    # Enforce cumulative duration constraint: sum(gaps + durations) <= event_dur_cs
    total_requested_cs = sum(raw_gaps_cs) + sum(raw_durations_cs)

    if total_requested_cs > event_dur_cs:
        # Scale down gaps and durations proportionally, guaranteeing each word >= 1cs
        excess = total_requested_cs - event_dur_cs

        # First, eliminate inter-word gaps if needed
        for i in range(len(raw_gaps_cs)):
            if excess <= 0:
                break
            can_cut = raw_gaps_cs[i]
            cut = min(can_cut, excess)
            raw_gaps_cs[i] -= cut
            excess -= cut

        # Second, reduce durations of longest words while keeping each >= 1cs
        if excess > 0:
            for idx in sorted(range(k), key=lambda i: raw_durations_cs[i], reverse=True):
                if excess <= 0:
                    break
                can_reduce = raw_durations_cs[idx] - 1
                reduction = min(can_reduce, excess)
                raw_durations_cs[idx] -= reduction
                excess -= reduction

    # Absorb any remaining trailing duration into the last word so karaoke completes with dialogue
    used_cs = sum(raw_gaps_cs) + sum(raw_durations_cs)
    remaining_cs = event_dur_cs - used_cs
    if remaining_cs > 0:
        raw_durations_cs[-1] += remaining_cs

    # Assemble tagged karaoke string
    parts: List[str] = []
    for i, w in enumerate(valid_words):
        gap = raw_gaps_cs[i]
        dur = raw_durations_cs[i]
        sanitized_tok = sanitize_word_token(w["text"])

        # If there is a silence gap before the word, encode gap pause tag {\k<gap>}
        if gap > 0:
            parts.append(r"{\k" + str(gap) + r"}")

        # Karaoke tag with word text and trailing space
        parts.append(f"{{{karaoke_tag}{dur}}}{sanitized_tok}")
        if i < k - 1:
            parts.append(" ")

    return "".join(parts)


def generate_ass_document(
    track: SubtitleTrack,
    karaoke_tag: str = r"\kf",
    custom_title: Optional[str] = None,
) -> str:
    """Compiles a complete ASS v4.00+ document string from a SubtitleTrack and its SubtitleEvents.

    Returns:
        Canonical UTF-8 ASS document string.

    Raises:
        AssDocumentError: If track data is corrupted, inverted, or empty.
    """
    if not track:
        raise AssDocumentError("Cannot generate ASS document for null track.")

    title = custom_title or f"Clipsly - Clip {track.clip_id}"

    # 1. Script Info Section
    script_info = build_script_info_section(title=title)

    # 2. V4+ Styles Section
    styles_section = build_v4_styles_section(style_name=DEFAULT_STYLE_NAME)

    # 3. Events Section
    events_lines = [
        "[Events]",
        "Format: Layer, Start, End, Style, Name, MarginL, MarginR, MarginV, Effect, Text",
    ]

    # Sort events deterministically by sequence_index, then start_ms
    sorted_events = sorted(track.events or [], key=lambda e: (e.sequence_index, e.start_ms))

    for ev in sorted_events:
        # Calculate formatted ASS interval
        start_cs, end_cs, start_str, end_str = format_dialogue_interval(ev.start_ms, ev.end_ms)
        event_dur_cs = end_cs - start_cs

        # Parse words JSON
        words_data: Optional[List[Dict[str, Any]]] = None
        if ev.words_json and ev.words_json.strip():
            try:
                words_data = json.loads(ev.words_json)
            except Exception as e:
                logger.warning("Event %s words_json JSON parse failure: %s", ev.id, e)

        # Generate karaoke text payload
        dialogue_text = format_karaoke_dialogue_text(
            event_text=ev.text,
            words_data=words_data,
            event_start_ms=ev.start_ms,
            event_dur_cs=event_dur_cs,
            karaoke_tag=karaoke_tag,
        )

        style = ev.style_name or DEFAULT_STYLE_NAME
        dialogue_line = f"Dialogue: 0,{start_str},{end_str},{style},,0,0,0,,{dialogue_text}"
        events_lines.append(dialogue_line)

    document = "\n".join([script_info, styles_section, "\n".join(events_lines)]) + "\n"

    # Validate generated document
    validate_ass_document(document)
    return document


def validate_ass_document(document: str) -> None:
    """Validates structural compliance of a generated ASS document string."""
    if not document or not document.strip():
        raise AssDocumentError("Generated ASS document is empty.")

    required_markers = [
        "[Script Info]",
        "ScriptType: v4.00+",
        "PlayResX: 1080",
        "PlayResY: 1920",
        "[V4+ Styles]",
        "Format: Name, Fontname, Fontsize",
        "Style: Default",
        "[Events]",
        "Format: Layer, Start, End, Style",
    ]

    for marker in required_markers:
        if marker not in document:
            raise AssDocumentError(f"ASS document missing required structural marker: '{marker}'.")
